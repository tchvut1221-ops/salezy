/** Israeli sales culture — what makes interpretation different from Western frameworks. */
export const ISRAELI_SALES_CONTEXT = `הקשר תרבותי ישראלי (קריטי לדיוק הניתוח):

- ישראלים ישירים — small-talk ארוך נתפס כבזבוז זמן או חוסר עניין, לא כנימוס.
- קשר אישי משמעותי יותר מבשווקים מערביים — "דוגרי" ואותנטיות בונים אמון מהר.
- Price anchoring נפוץ — "אצל המתחרים זה יותר זול" זו טקטיקה, לא בהכרח אמת.
- דחיפות עובדת אבל חייבת להרגיש אמיתית, לא מיוצרת ("המבצע נגמר היום" שורף אמון).
- "אני צריך לחשוב" / "אני אחזור אליך" = כמעט תמיד התנגדות מנומסת, לא צורך אמיתי בזמן.
- "תשלח לי במייל" לרוב dודחייה (deflection), לא עניין אמיתי.
- סוף שבוע הוא שישי-שבת — אל תדחוף להחלטה ל"מחר" ביום חמישי בערב.
- חוצפה חיובית: לקוח ישראלי מכבד איש מכירות שעומד על שלו ומאתגר אותו בכבוד.`;

